"""Generate Dart colors from the platform-neutral design source."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
tokens = json.loads((root / 'shared/design-tokens.json').read_text())
lines = ["// Generated by scripts/generate_design_tokens.py. Do not edit.",
         "import 'package:material_ui/material_ui.dart';", '', 'abstract final class AppColors {']
for key, value in tokens.items():
    if len(value) != 6 or any(c not in '0123456789abcdefABCDEF' for c in value):
        raise ValueError(f'Invalid color: {key}')
    lines.append(f'  static const {key} = Color(0xff{value.lower()});')
lines.append('}')
(root / 'flutter_app/lib/ui/design_tokens.dart').write_text('\n'.join(lines) + '\n')
